using System.Security.Cryptography;
using System.Text;

// Generates src/PerformativeMail.Sim/Primitives/TrigQ15.g.cs: 4096 entries,
// table[i] = round-half-away-from-zero(32767 * sin(2 * pi * i / 4096)) (ADR-0006 section 6).
// Prints the SHA-256 of the table's 8192 little-endian bytes; that digest is pinned in the
// story's Implementation Notes and in TrigQ15Tests.
//
// Also generates src/PerformativeMail.Sim/Primitives/AtanQ15.g.cs (ADR-0013 section 3): 1025 ushort BAM
// entries, atan[i] = round-half-away-from-zero(atan(i / 1024) * 65536 / (2 * pi)), i = 0 ... 1024.
// Prints the SHA-256 of its 2050 little-endian bytes (pinned in Atan2BamTests).
// Usage: GenTrigQ15 [sineOutputPath [atanOutputPath]]

const int EntryCount = 4096;
const int PerLine = 16;

string outputPath = args.Length > 0 ? args[0] : Path.Combine(FindRepoRoot(), "src", "PerformativeMail.Sim", "Primitives", "TrigQ15.g.cs");

short[] table = new short[EntryCount];
for (int i = 0; i < EntryCount; i++)
{
    double angle = 2.0 * Math.PI * i / EntryCount;
    double scaled = 32767.0 * Math.Sin(angle);
    table[i] = checked((short)Math.Round(scaled, MidpointRounding.AwayFromZero));
}

byte[] bytes = new byte[EntryCount * 2];
for (int i = 0; i < EntryCount; i++)
{
    bytes[2 * i] = (byte)(table[i] & 0xFF);
    bytes[2 * i + 1] = (byte)((table[i] >> 8) & 0xFF);
}

string digest = Convert.ToHexString(SHA256.HashData(bytes));

var sb = new StringBuilder();
sb.Append("// <auto-generated>\n");
sb.Append("// Generated by tools/GenTrigQ15 (ADR-0006 section 6). DO NOT EDIT; the table is pinned by\n");
sb.Append("// TrigQ15Tests (SHA-256 of the 8192 little-endian bytes). Regenerate only by deliberate decision.\n");
sb.Append("// table[i] = round-half-away-from-zero(32767 * sin(2 * pi * i / 4096)), i = 0 ... 4095.\n");
sb.Append("// </auto-generated>\n");
sb.Append('\n');
sb.Append("using System.Runtime.CompilerServices;\n");
sb.Append('\n');
sb.Append("namespace PerformativeMail.Sim.Primitives;\n");
sb.Append('\n');
sb.Append("public static partial class TrigQ15\n");
sb.Append("{\n");
sb.Append("    // ReadOnlySpan literal property: the data lives in the PE image, no static field (ADR-0003 section 4).\n");
sb.Append("    // AggressiveOptimization: at Tier-0 the runtime's RuntimeHelpers.CreateSpan fallback allocates ~64 B per\n");
sb.Append("    // call; jitting this getter fully optimised from the first call makes the span a plain pointer + length.\n");
sb.Append("    private static ReadOnlySpan<short> Table\n");
sb.Append("    {\n");
sb.Append("        [MethodImpl(MethodImplOptions.AggressiveOptimization)]\n");
sb.Append("        get => new short[]\n");
sb.Append("        {\n");
for (int row = 0; row < EntryCount / PerLine; row++)
{
    sb.Append("            ");
    for (int col = 0; col < PerLine; col++)
    {
        sb.Append(table[row * PerLine + col]);
        sb.Append(row == EntryCount / PerLine - 1 && col == PerLine - 1 ? "" : ",");
        if (col != PerLine - 1)
        {
            sb.Append(' ');
        }
    }

    sb.Append('\n');
}

sb.Append("        };\n");
sb.Append("    }\n");
sb.Append("}\n");

File.WriteAllText(outputPath, sb.ToString(), new UTF8Encoding(false));
Console.WriteLine($"Wrote {outputPath}");
Console.WriteLine($"TrigQ15 SHA-256: {digest}");

const int AtanCount = 1025;
string atanPath = args.Length > 1 ? args[1] : Path.Combine(FindRepoRoot(), "src", "PerformativeMail.Sim", "Primitives", "AtanQ15.g.cs");
ushort[] atan = new ushort[AtanCount];
for (int i = 0; i < AtanCount; i++)
{
    double bam = Math.Atan(i / 1024.0) * 65536.0 / (2.0 * Math.PI);
    atan[i] = checked((ushort)Math.Round(bam, MidpointRounding.AwayFromZero));
}

byte[] atanBytes = new byte[AtanCount * 2];
for (int i = 0; i < AtanCount; i++)
{
    atanBytes[2 * i] = (byte)(atan[i] & 0xFF);
    atanBytes[2 * i + 1] = (byte)((atan[i] >> 8) & 0xFF);
}

string atanDigest = Convert.ToHexString(SHA256.HashData(atanBytes));

var ab = new StringBuilder();
ab.Append("// <auto-generated>\n");
ab.Append("// Generated by tools/GenTrigQ15 (ADR-0013 section 3). DO NOT EDIT; the table is pinned by\n");
ab.Append("// Atan2BamTests (SHA-256 of the 2050 little-endian bytes). Regenerate only by deliberate decision.\n");
ab.Append("// AtanTable[i] = round-half-away-from-zero(atan(i / 1024) * 65536 / (2 * pi)), i = 0 ... 1024.\n");
ab.Append("// </auto-generated>\n");
ab.Append('\n');
ab.Append("using System.Runtime.CompilerServices;\n");
ab.Append('\n');
ab.Append("namespace PerformativeMail.Sim.Primitives;\n");
ab.Append('\n');
ab.Append("public static partial class TrigQ15\n");
ab.Append("{\n");
ab.Append("    // ReadOnlySpan literal property: the data lives in the PE image, no static field (ADR-0003 section 4).\n");
ab.Append("    // AggressiveOptimization: same reasoning as Table in TrigQ15.g.cs (TD-008).\n");
ab.Append("    internal static ReadOnlySpan<ushort> AtanTable\n");
ab.Append("    {\n");
ab.Append("        [MethodImpl(MethodImplOptions.AggressiveOptimization)]\n");
ab.Append("        get => new ushort[]\n");
ab.Append("        {\n");
for (int i = 0; i < AtanCount; i += PerLine)
{
    ab.Append("            ");
    int end = Math.Min(i + PerLine, AtanCount);
    for (int j = i; j < end; j++)
    {
        ab.Append(atan[j]);
        ab.Append(j == AtanCount - 1 ? "" : ",");
        if (j != end - 1)
        {
            ab.Append(' ');
        }
    }

    ab.Append('\n');
}

ab.Append("        };\n");
ab.Append("    }\n");
ab.Append("}\n");

File.WriteAllText(atanPath, ab.ToString(), new UTF8Encoding(false));
Console.WriteLine($"Wrote {atanPath}");
Console.WriteLine($"AtanQ15 SHA-256: {atanDigest}");
return 0;

static string FindRepoRoot()
{
    DirectoryInfo? dir = new DirectoryInfo(Directory.GetCurrentDirectory());
    while (dir != null)
    {
        if (File.Exists(Path.Combine(dir.FullName, "PerformativeMail.sln")))
        {
            return dir.FullName;
        }

        dir = dir.Parent;
    }

    throw new InvalidOperationException("PerformativeMail.sln not found above the current directory; pass an output path.");
}
